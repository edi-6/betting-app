ROWS = 8


def _glyph(ch):
    rows = _G.get(ch, _G['?'])
    w = len(rows[0])
    g = np.zeros((ROWS, w), bool)
    for r, row in enumerate(rows):
        for c, x in enumerate(row):
            g[r, c] = x == '#'
    return g


def text_mask(text):
    """(8, W) bool bitmap of a line of text (1 font pixel between glyphs)."""
    cols = []
    for k, ch in enumerate(text):
        g = _glyph(ch)
        cols.append(g)
        if k < len(text) - 1:
            cols.append(np.zeros((ROWS, 1), bool))
    return np.concatenate(cols, 1) if cols else np.zeros((ROWS, 1), bool)


def render(text, px=4, color=(255, 255, 255), shadow=True, outline=0, outline_col=(16, 12, 20), grad=None):
    """RGBA uint8 sprite of the text at px screen pixels per font pixel, with the game's drop shadow and an
    optional dark outline (in font pixels) for legibility over video. grad: (top, bottom) colours."""
    m = text_mask(text)
    h, w = m.shape
    pad = 1 + outline
    H, W = (h + 2 * pad), (w + 2 * pad)
    col = np.zeros((H, W, 3), float)
    alpha = np.zeros((H, W), float)
    if outline:
        o = np.zeros((H, W), bool)
        for dy in range(-outline, outline + 1):
            for dx in range(-outline, outline + 1):
                o[pad + dy:pad + dy + h, pad + dx:pad + dx + w] |= m
        o2 = o.copy()
        o2[1:, 1:] |= o[:-1, :-1]
        col[o2] = outline_col
        alpha[o2] = 1.0
    if shadow:
        sh = np.zeros((H, W), bool)
        sh[pad + 1:pad + 1 + h, pad + 1:pad + 1 + w] = m[:H - pad - 1, :W - pad - 1][:h, :w]
        col[sh] = np.array(color, float) * 0.25
        alpha[sh] = 1.0
    body = np.zeros((H, W), bool)
    body[pad:pad + h, pad:pad + w] = m
    if grad is not None:
        t = np.linspace(0, 1, h)[:, None]
        g = np.array(grad[0], float) * (1 - t[..., None]) + np.array(grad[1], float) * t[..., None]
        colbody = np.zeros((H, W, 3))
        colbody[pad:pad + h, pad:pad + w] = g
        col[body] = colbody[body]
    else:
        col[body] = color
    alpha[body] = 1.0
    out = np.zeros((H, W, 4), np.uint8)
    out[..., :3] = np.clip(col, 0, 255)
    out[..., 3] = (alpha * 255).astype(np.uint8)
    return np.kron(out, np.ones((px, px, 1), np.uint8))
